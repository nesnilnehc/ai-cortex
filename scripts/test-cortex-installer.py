#!/usr/bin/env python3
"""Integration regressions for cortex-owned links and version resynchronization.

Runs the real POSIX shell entry point against small versioned asset fixtures,
per-test homes and local Git origins. No user IDE files or network are used.
"""

from __future__ import annotations

import os
from pathlib import Path
import shutil
import subprocess
import tempfile
import unittest


ROOT = Path(__file__).resolve().parents[1]
INSTALLER = ROOT / 'bin' / 'cortex'
MARKER = '<!-- generated by cortex -->'


class InstallerTests(unittest.TestCase):
    def setUp(self):
        self.workspace = tempfile.TemporaryDirectory(prefix='cortex-installer-')
        self.addCleanup(self.workspace.cleanup)
        self.root = Path(self.workspace.name).resolve()
        self.home = self.root / 'home'
        self.source = self.root / 'cortex'
        self.bootstrap = self.root / 'fixed-installer'
        shutil.copyfile(INSTALLER, self.bootstrap)
        self.bootstrap.chmod(0o755)
        (self.source / 'bin').mkdir(parents=True)
        shutil.copyfile(INSTALLER, self.source / 'bin/cortex')
        (self.source / 'bin/cortex').chmod(0o755)
        (self.source / 'AGENTS.md').write_text('# Fixture\n')
        (self.source / 'skills').mkdir()
        (self.source / 'skills/INDEX.md').write_text('# Fixture skills\n')
        (self.source / 'rules').mkdir()
        (self.source / 'rules/INDEX.md').write_text('# Fixture rules\n')
        (self.source / 'specs').mkdir()
        (self.source / 'protocols').mkdir()
        self.add_skill('kept')
        self.add_rule('global', 'user')
        self.add_rule('on-demand', 'project')
        for directory in ('.agents/skills', '.claude/skills', '.claude/rules',
                          '.cursor/skills', '.cursor/rules'):
            (self.home / directory).mkdir(parents=True, exist_ok=True)
        self.env = dict(os.environ, HOME=str(self.home), CORTEX_HOME=str(self.source),
                        XDG_DATA_HOME=str(self.home / '.local/share'),
                        GIT_CONFIG_GLOBAL=os.devnull, GIT_CONFIG_NOSYSTEM='1',
                        GIT_TERMINAL_PROMPT='0', GIT_ALLOW_PROTOCOL='file')
        for key in ('GIT_DIR', 'GIT_WORK_TREE', 'GIT_INDEX_FILE', 'GIT_COMMON_DIR'):
            self.env.pop(key, None)

    def assert_link_target(self, link, target):
        self.assertTrue(link.is_symlink(), f'Expected preserved link at {link}; it was removed')
        self.assertEqual(link.readlink(), target)

    def add_skill(self, name):
        directory = self.source / 'skills' / name
        directory.mkdir()
        (directory / 'SKILL.md').write_text(f'---\nname: {name}\ndescription: Fixture\n---\n')

    def add_rule(self, name, scope):
        (self.source / 'rules' / f'{name}.md').write_text(
            f'---\nname: {name}\nrecommended_scope: {scope}\n---\n# Rule: {name}\n\nFixture body.\n')

    def cli(self, *args, success=True):
        result = subprocess.run([str(self.bootstrap), *args], env=self.env, cwd=self.root,
                                stdout=subprocess.PIPE, stderr=subprocess.STDOUT,
                                text=True, timeout=30)
        if success:
            self.assertEqual(result.returncode, 0, result.stdout)
        return result

    def git(self, *args):
        result = subprocess.run(['git', '-C', str(self.source), *args], env=self.env,
                                stdout=subprocess.PIPE, stderr=subprocess.STDOUT,
                                text=True, timeout=30)
        self.assertEqual(result.returncode, 0, result.stdout)
        return result.stdout.strip()

    def init_source(self):
        self.git('init', '--initial-branch=main')
        self.git('config', 'user.name', 'Installer Test')
        self.git('config', 'user.email', 'installer@example.invalid')
        self.git('add', '.')
        self.git('commit', '-m', 'Old asset set')
        return self.git('rev-parse', 'HEAD')

    def release_origin(self):
        old = self.init_source()
        self.git('tag', '-a', 'v1.2.0', '-m', 'Stable old')
        self.add_skill('released')
        self.git('add', '.')
        self.git('commit', '-m', 'Stable new')
        stable = self.git('rev-parse', 'HEAD')
        self.git('tag', 'v1.10.0')
        self.add_skill('development')
        self.git('add', '.')
        self.git('commit', '-m', 'Development')
        self.git('tag', 'v2.0.0-rc.1')
        self.git('tag', 'v01.99.0')
        origin = self.root / 'origin.git'
        self.git('clone', '--bare', str(self.source), str(origin))
        self.git('remote', 'add', 'origin', str(origin))
        return old, stable

    def test_upgrade_selects_highest_remote_stable_and_resyncs(self):
        _, stable = self.release_origin()
        self.git('tag', 'v99.0.0')  # Local-only tags must not affect selection.
        self.cli('install')
        self.cli('upgrade')
        self.assertEqual(self.git('rev-parse', 'HEAD'), stable)
        self.assertEqual(self.git('branch', '--show-current'), '')
        self.assertTrue((self.home / '.agents/skills/released').is_symlink())
        self.assertFalse((self.home / '.agents/skills/development').is_symlink())
        self.cli('upgrade')  # Repeat selection is safe.
        self.assertEqual(self.git('rev-parse', 'HEAD'), stable)

    def test_upgrade_selects_explicit_version_and_update_still_follows_main(self):
        old, _ = self.release_origin()
        main = self.git('rev-parse', 'HEAD')
        self.cli('upgrade', '1.2.0')
        self.assertEqual(self.git('rev-parse', 'HEAD'), old)
        self.cli('upgrade', 'v1.2.0')
        self.assertEqual(self.git('rev-parse', 'HEAD'), old)
        self.cli('update')
        self.assertEqual(self.git('rev-parse', 'HEAD'), main)

    def test_upgrade_refuses_dirty_checkout_without_switching(self):
        self.release_origin()
        head = self.git('rev-parse', 'HEAD')
        (self.source / 'untracked').write_text('keep')
        result = self.cli('upgrade', success=False)
        self.assertNotEqual(result.returncode, 0)
        self.assertIn('dirty', result.stdout.lower())
        self.assertEqual(self.git('rev-parse', 'HEAD'), head)
        self.assertEqual((self.source / 'untracked').read_text(), 'keep')

    def test_upgrade_rejects_invalid_missing_or_unavailable_versions(self):
        self.release_origin()
        head = self.git('rev-parse', 'HEAD')
        for args in [('v2.0.0-rc.1',), ('01.2.0',), ('--force',),
                     ('1.2',), ('1.2.0', 'extra'), ('9.0.0',)]:
            with self.subTest(args=args):
                self.assertNotEqual(self.cli('upgrade', *args, success=False).returncode, 0)
                self.assertEqual(self.git('rev-parse', 'HEAD'), head)
        self.git('remote', 'set-url', 'origin', str(self.root / 'missing.git'))
        self.assertNotEqual(self.cli('upgrade', success=False).returncode, 0)
        self.assertEqual(self.git('rev-parse', 'HEAD'), head)

    def test_upgrade_does_not_use_local_tags_when_origin_has_no_stable_tag(self):
        self.release_origin()
        self.git('push', 'origin', ':refs/tags/v1.2.0', ':refs/tags/v1.10.0')
        head = self.git('rev-parse', 'HEAD')
        self.assertNotEqual(self.cli('upgrade', success=False).returncode, 0)
        self.assertEqual(self.git('rev-parse', 'HEAD'), head)

    def test_upgrade_rejects_moved_release_tag(self):
        _, stable = self.release_origin()
        self.cli('upgrade')
        self.git('tag', '-f', 'v1.10.0', 'main')
        self.git('push', '--force', 'origin', 'refs/tags/v1.10.0')
        result = self.cli('upgrade', success=False)
        self.assertNotEqual(result.returncode, 0)
        self.assertIn('changed', result.stdout)
        self.assertEqual(self.git('rev-parse', 'HEAD'), stable)

    def test_upgrade_rejects_release_without_required_assets(self):
        self.release_origin()
        self.git('rm', 'skills/INDEX.md')
        self.git('commit', '-m', 'Invalid release')
        head = self.git('rev-parse', 'HEAD')
        self.git('tag', 'v3.0.0')
        self.git('push', 'origin', 'refs/tags/v3.0.0')
        result = self.cli('upgrade', success=False)
        self.assertNotEqual(result.returncode, 0)
        self.assertIn('required file', result.stdout)
        self.assertEqual(self.git('rev-parse', 'HEAD'), head)

    def test_legacy_entry_dry_run_preserves_old_and_personal_entries(self):
        legacy = self.home / '.claude/skills/ai-cortex'
        legacy.mkdir()
        (legacy / 'manifest.json').write_text('{"legacy":true}')
        personal = self.home / '.claude/skills/personal'
        personal.mkdir()
        (personal / 'notes').write_text('Keep')
        self.cli('clean', '--dry-run')
        self.assertEqual((legacy / 'manifest.json').read_text(), '{"legacy":true}')
        self.assertEqual((personal / 'notes').read_text(), 'Keep')

    def test_legacy_entry_migration_installs_canonical_skills_and_is_repeatable(self):
        for ide in ['.claude', '.cursor']:
            legacy = self.home / ide / 'skills/ai-cortex'
            legacy.mkdir()
            (legacy / 'manifest.json').write_text('{"legacy":true}')
            personal = self.home / ide / 'skills/personal'
            personal.mkdir()
            (personal / 'notes').write_text('Keep')
        self.cli('clean', '--yes')
        self.cli('install')
        self.cli('clean', '--dry-run')
        self.cli('install')
        for ide in ['.claude', '.cursor']:
            self.assertFalse((self.home / ide / 'skills/ai-cortex').exists())
            self.assert_link_target(self.home / ide / 'skills/kept', self.source / 'skills/kept')
            self.assertEqual((self.home / ide / 'skills/personal/notes').read_text(), 'Keep')
        self.assertTrue((self.source / 'AGENTS.md').is_file())

    def test_rule_link_is_preserved_when_target_is_foreign(self):
        """Covers: README ownership contract; same-name rule regression."""
        foreign = self.root / 'personal-rule.md'
        foreign.write_text('Personal rule\n')
        link = self.home / '.claude/rules/global.md'
        link.symlink_to(foreign)

        self.cli('install')

        self.assert_link_target(link, foreign)
        self.assertEqual(foreign.read_text(), 'Personal rule\n')

    def test_rule_link_is_preserved_when_foreign_target_is_missing(self):
        """Covers: foreign-rule ownership applies to broken links too."""
        foreign = self.root / 'missing-rule.md'
        link = self.home / '.claude/rules/global.md'
        link.symlink_to(foreign)

        self.cli('install')

        self.assert_link_target(link, foreign)
        self.assertFalse(foreign.exists())

    def test_skill_link_is_preserved_when_target_has_similar_prefix(self):
        """Covers: an adjacent checkout is not owned by this source."""
        foreign = Path(str(self.source) + '-other') / 'skills/kept'
        foreign.mkdir(parents=True)
        link = self.home / '.agents/skills/kept'
        link.symlink_to(foreign)

        self.cli('install')

        self.assert_link_target(link, foreign)

    def test_uninstall_preserves_links_when_targets_have_similar_prefix(self):
        """Covers: uninstall removes only Cortex-owned links."""
        foreign = Path(str(self.source) + '-other')
        (foreign / 'skills/mine').mkdir(parents=True)
        (foreign / 'rules').mkdir()
        (foreign / 'rules/mine.md').write_text('Personal rule\n')
        skill = self.home / '.agents/skills/mine'
        rule = self.home / '.claude/rules/mine.md'
        skill.symlink_to(foreign / 'skills/mine')
        rule.symlink_to(foreign / 'rules/mine.md')

        self.cli('uninstall', '--yes')

        self.assert_link_target(skill, foreign / 'skills/mine')
        self.assert_link_target(rule, foreign / 'rules/mine.md')
        self.assertEqual((foreign / 'rules/mine.md').read_text(), 'Personal rule\n')

    def test_uninstall_preserves_link_when_target_escapes_source_lexically(self):
        """Covers: lexical traversal cannot establish managed ownership."""
        foreign = self.source / 'skills/../../outside'
        link = self.home / '.agents/skills/mine'
        link.symlink_to(foreign)

        self.cli('uninstall', '--yes')

        self.assert_link_target(link, foreign)

    def test_prune_preserves_broken_links_when_targets_are_foreign(self):
        """Covers: automatic resync must not clean another checkout's links."""
        foreign = Path(str(self.source) + '-other') / 'skills/missing'
        link = self.home / '.agents/skills/missing'
        link.symlink_to(foreign)

        self.cli('install')

        self.assert_link_target(link, foreign)

    def test_on_demand_cleanup_preserves_link_when_target_is_foreign(self):
        """Covers: changing rule scope grants no authority over user links."""
        foreign = Path(str(self.source) + '-other') / 'rules/on-demand.md'
        foreign.parent.mkdir(parents=True)
        foreign.write_text('Personal rule\n')
        link = self.home / '.claude/rules/on-demand.md'
        link.symlink_to(foreign)

        self.cli('install')

        self.assert_link_target(link, foreign)

    def test_cursor_rule_is_preserved_when_file_has_no_generated_marker(self):
        """Covers: existing user-owned Cursor rules are not replaced."""
        rule = self.home / '.cursor/rules/global.mdc'
        rule.write_text('Personal Cursor rule\n')

        self.cli('install')

        self.assertEqual(rule.read_text(), 'Personal Cursor rule\n')

    def test_cursor_rule_is_preserved_when_link_points_to_marked_foreign_file(self):
        """Covers: install never writes through a foreign Cursor rule link."""
        foreign = self.root / 'personal.mdc'
        content = MARKER + '\nPersonal linked content\n'
        foreign.write_text(content)
        link = self.home / '.cursor/rules/global.mdc'
        link.symlink_to(foreign)

        self.cli('install')

        self.assert_link_target(link, foreign)
        self.assertEqual(foreign.read_text(), content)

    def test_uninstall_preserves_cursor_link_when_foreign_file_is_marked(self):
        """Covers: a copied marker on a foreign target does not own its link."""
        foreign = self.root / 'personal.mdc'
        foreign.write_text(MARKER + '\nPersonal content\n')
        link = self.home / '.cursor/rules/mine.mdc'
        link.symlink_to(foreign)

        self.cli('uninstall', '--yes')

        self.assert_link_target(link, foreign)
        self.assertEqual(foreign.read_text(), MARKER + '\nPersonal content\n')

    def test_install_is_idempotent_when_assets_are_managed(self):
        """Covers: repeat installation refreshes only the managed asset set."""
        self.cli('install')
        rule = self.home / '.cursor/rules/global.mdc'
        original = rule.read_bytes()

        self.cli('install')

        for ide in ('.agents', '.claude', '.cursor'):
            self.assertEqual((self.home / ide / 'skills/kept').resolve(), self.source / 'skills/kept')
        self.assertEqual(rule.read_bytes(), original)
        self.assertFalse((self.home / '.cursor/rules/on-demand.mdc').exists())

    def test_cursor_rule_is_refreshed_when_managed_source_changes(self):
        """Covers: protecting foreign rules must not disable managed refresh."""
        self.cli('install')
        rule = self.source / 'rules/global.md'
        rule.write_text(rule.read_text() + 'Revised managed body.\n')

        self.cli('install')

        generated = (self.home / '.cursor/rules/global.mdc').read_text()
        self.assertEqual(generated.splitlines()[0], MARKER)
        self.assertIn('Revised managed body.', generated)

    def test_resync_removes_global_install_when_rule_becomes_on_demand(self):
        """Covers: selected scope changes remove managed global copies only."""
        self.cli('install')
        self.assertTrue((self.home / '.claude/rules/global.md').is_symlink())
        self.assertTrue((self.home / '.cursor/rules/global.mdc').is_file())
        self.add_rule('global', 'project')

        self.cli('install')

        self.assertFalse((self.home / '.claude/rules/global.md').is_symlink())
        self.assertFalse((self.home / '.cursor/rules/global.mdc').exists())
        self.assertTrue((self.source / 'rules/global.md').is_file())

    def test_resync_prunes_obsolete_assets_when_source_revision_rolls_back(self):
        """Covers: rollback removes links/translations from the newer version."""
        old = self.init_source()
        self.add_skill('newer')
        self.add_rule('newer', 'user')
        self.git('add', '.')
        self.git('commit', '-m', 'Newer asset set')
        self.cli('install')
        self.assertEqual((self.home / '.agents/skills/newer').resolve(), self.source / 'skills/newer')
        self.assertTrue((self.home / '.cursor/rules/newer.mdc').is_file())

        self.git('checkout', '--detach', old)
        self.cli('install')

        for ide in ('.agents', '.claude', '.cursor'):
            self.assertEqual(sorted(p.name for p in (self.home / ide / 'skills').iterdir()), ['kept'])
        self.assertEqual(sorted(p.name for p in (self.home / '.claude/rules').iterdir()), ['global.md'])
        self.assertEqual(sorted(p.name for p in (self.home / '.cursor/rules').iterdir()), ['global.mdc'])

    def test_update_prunes_managed_links_but_preserves_foreign_prefix_links(self):
        """Covers: update uses the same ownership boundary as install/uninstall."""
        self.init_source()
        remote = self.root / 'origin.git'
        result = subprocess.run(['git', 'clone', '--bare', str(self.source), str(remote)],
                                env=self.env, capture_output=True, text=True, timeout=30)
        self.assertEqual(result.returncode, 0, result.stderr)
        self.git('remote', 'add', 'origin', str(remote))
        self.git('fetch', 'origin')
        self.git('remote', 'set-head', 'origin', 'main')
        foreign = Path(str(self.source) + '-other') / 'skills/missing'
        foreign_link = self.home / '.agents/skills/foreign'
        foreign_link.symlink_to(foreign)
        stale = self.home / '.agents/skills/deleted'
        stale.symlink_to(self.source / 'skills/deleted')

        self.cli('update')

        self.assert_link_target(foreign_link, foreign)
        self.assertFalse(stale.is_symlink())
        self.assertTrue((self.home / '.agents/skills/kept').exists())

    def test_uninstall_removes_managed_links_when_source_path_has_pattern_characters(self):
        """Covers: managed ownership is literal even for spaces and glob characters."""
        renamed = self.root / 'cortex [fixture].data'
        self.source.rename(renamed)
        self.source = renamed
        self.env['CORTEX_HOME'] = str(renamed)
        self.cli('install')

        self.cli('uninstall', '--yes')

        self.assertFalse((self.home / '.agents/skills/kept').is_symlink())
        self.assertFalse((self.home / '.claude/rules/global.md').is_symlink())
        self.assertTrue((self.source / 'skills/kept/SKILL.md').is_file())

    def test_uninstall_removes_managed_links_when_source_override_has_trailing_slashes(self):
        """Covers: a directory spelling with trailing separators has the same owner."""
        self.env['CORTEX_HOME'] = str(self.source) + '///'
        self.cli('install')

        self.cli('uninstall', '--yes')

        self.assertFalse((self.home / '.agents/skills/kept').is_symlink())
        self.assertFalse((self.home / '.claude/rules/global.md').is_symlink())

    def test_cursor_rule_is_preserved_when_marker_only_appears_in_body(self):
        """Covers: quoting a generated marker does not establish file ownership."""
        rule = self.home / '.cursor/rules/global.mdc'
        content = 'Personal instructions\n' + MARKER + '\n'
        rule.write_text(content)

        self.cli('install')

        self.assertEqual(rule.read_text(), content)

    def test_status_excludes_cursor_link_when_foreign_target_has_marker(self):
        """Covers: status reports only managed generated Cursor files."""
        foreign = self.root / 'personal.mdc'
        foreign.write_text(MARKER + '\nPersonal content\n')
        (self.home / '.cursor/rules/global.mdc').symlink_to(foreign)

        result = self.cli('status')

        self.assertRegex(result.stdout, r'Cursor: 0/\d+ \.mdc generated')

    def test_update_refuses_change_when_checkout_is_dirty(self):
        """Covers: local edits survive update without --force."""
        self.init_source()
        user_file = self.source / 'personal.txt'
        user_file.write_text('Keep this change\n')

        result = self.cli('update', success=False)

        self.assertNotEqual(result.returncode, 0)
        self.assertIn('Working tree dirty', result.stdout)
        self.assertEqual(user_file.read_text(), 'Keep this change\n')

    def test_install_preserves_real_files_when_users_own_destinations(self):
        """Covers: real user skill directories and command files are retained."""
        directory = self.home / '.agents/skills/kept'
        directory.mkdir()
        (directory / 'mine').write_text('Keep\n')
        command = self.home / '.local/bin/cortex'
        command.parent.mkdir(parents=True)
        command.write_text('Personal command\n')

        self.cli('install')

        self.assertEqual((directory / 'mine').read_text(), 'Keep\n')
        self.assertEqual(command.read_text(), 'Personal command\n')

    def test_uninstall_removes_managed_assets_when_user_content_is_unrelated(self):
        """Covers: uninstall removes managed files but keeps clone/user content."""
        self.cli('install')
        personal = self.home / '.claude/rules/personal.md'
        personal.write_text('Keep\n')

        self.cli('uninstall', '--yes')

        self.assertEqual(personal.read_text(), 'Keep\n')
        self.assertFalse((self.home / '.agents/skills/kept').is_symlink())
        self.assertFalse((self.home / '.claude/rules/global.md').is_symlink())
        self.assertFalse((self.home / '.cursor/rules/global.mdc').exists())
        self.assertFalse((self.home / '.local/bin/cortex').is_symlink())
        self.assertTrue((self.source / 'skills/kept/SKILL.md').is_file())


if __name__ == '__main__':
    unittest.main(verbosity=2)
